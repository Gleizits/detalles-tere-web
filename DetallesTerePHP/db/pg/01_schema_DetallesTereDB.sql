-- DetallesTereTS — esquema PostgreSQL para Neon (equivalente a 01_schema SQL Server).
-- Ejecutar ya conectado a DetallesTereDB, con el rol owner del proyecto.
CREATE EXTENSION IF NOT EXISTS citext;
CREATE SCHEMA IF NOT EXISTS dbo;

-- Reemplaza SYSUTCDATETIME() de T-SQL. Devuelve timestamp sin zona en UTC.
CREATE OR REPLACE FUNCTION dbo.utcnow()
RETURNS timestamp(2)
LANGUAGE sql STABLE
AS $$ SELECT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::timestamp(2) $$;

-- 1. USUARIO
CREATE TABLE IF NOT EXISTS dbo.USUARIO (
    ID_USUARIO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME   CITEXT       NOT NULL,
    NOMBRE     VARCHAR(50)  NOT NULL,
    APELLIDO   VARCHAR(50)  NOT NULL,
    CORREO     CITEXT       NULL,
    CONTRASENA VARCHAR(255) NOT NULL,
    ROL        VARCHAR(12)  NOT NULL,
    ESTADO     SMALLINT     NOT NULL DEFAULT 1 CHECK (ESTADO IN (0,1)),
    CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UQ_USUARIO_CORREO   UNIQUE (CORREO),
    CONSTRAINT CK_USUARIO_ROL CHECK (ROL IN ('admin','empleado'))
);

-- 2. CAJA
CREATE TABLE IF NOT EXISTS dbo.CAJA (
    ID_CAJA        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO     INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    MONTO_INICIAL  NUMERIC(10,2) NOT NULL CHECK (MONTO_INICIAL >= 0 AND MONTO_INICIAL <= 1000000),
    MONTO_FINAL    NUMERIC(10,2) NULL CHECK (MONTO_FINAL   >= 0 AND MONTO_FINAL   <= 1000000),
    MONTO_REAL     NUMERIC(10,2) NULL CHECK (MONTO_REAL    >= 0 AND MONTO_REAL    <= 1000000),
    DIFERENCIA     NUMERIC(10,2) NULL,
    FECHA_APERTURA TIMESTAMP(2)  NOT NULL,
    FECHA_CIERRE   TIMESTAMP(2)  NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS UX_CAJA_ABIERTA
    ON dbo.CAJA (ID_USUARIO) WHERE FECHA_CIERRE IS NULL;

-- 3. CATEGORIA
CREATE TABLE IF NOT EXISTS dbo.CATEGORIA (
    ID_CATEGORIA INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE       VARCHAR(100) NOT NULL,
    DESCRIPCION  VARCHAR(256) NULL
);

-- 4. MATERIAL (antes que PRODUCTO: PRODUCTO referencia ID_MATERIAL)
CREATE TABLE IF NOT EXISTS dbo.MATERIAL (
    ID_MATERIAL   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CATEGORIA  INT NULL REFERENCES dbo.CATEGORIA(ID_CATEGORIA),
    NOMBRE        VARCHAR(50)  NOT NULL,
    TIPO          VARCHAR(50)  NULL,
    PRECIO_COMPRA NUMERIC(10,2) NULL CHECK (PRECIO_COMPRA >= 0 AND PRECIO_COMPRA <= 1000000),
    PRECIO_VENTA  NUMERIC(10,2) NOT NULL CHECK (PRECIO_VENTA  >= 0 AND PRECIO_VENTA  <= 1000000),
    ESTADO        SMALLINT NOT NULL DEFAULT 1 CHECK (ESTADO IN (0,1))
);

-- 5. PRODUCTO
CREATE TABLE IF NOT EXISTS dbo.PRODUCTO (
    ID_PRODUCTO   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CATEGORIA  INT NULL REFERENCES dbo.CATEGORIA(ID_CATEGORIA),
    ID_MATERIAL   INT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    NOMBRE        VARCHAR(50)  NOT NULL,
    TIPO          VARCHAR(50)  NULL,
    PRECIO_COMPRA NUMERIC(10,2) NULL CHECK (PRECIO_COMPRA >= 0 AND PRECIO_COMPRA <= 1000000),
    PRECIO_VENTA  NUMERIC(10,2) NOT NULL CHECK (PRECIO_VENTA  >= 0 AND PRECIO_VENTA  <= 1000000),
    ESTADO        SMALLINT NOT NULL DEFAULT 1 CHECK (ESTADO IN (0,1))
);

-- 6. ARREGLO
CREATE TABLE IF NOT EXISTS dbo.ARREGLO (
    ID_DETALLE    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CATEGORIA  INT NULL REFERENCES dbo.CATEGORIA(ID_CATEGORIA),
    NOMBRE        VARCHAR(100) NOT NULL,
    PRECIO_COMPRA NUMERIC(10,2) NULL CHECK (PRECIO_COMPRA >= 0 AND PRECIO_COMPRA <= 1000000),
    PRECIO_VENTA  NUMERIC(10,2) NOT NULL CHECK (PRECIO_VENTA  >= 0 AND PRECIO_VENTA  <= 1000000),
    ESTADO        SMALLINT NOT NULL DEFAULT 1 CHECK (ESTADO IN (0,1))
);

-- 7. DETALLE_ARREGLO
CREATE TABLE IF NOT EXISTS dbo.DETALLE_ARREGLO (
    ID_DETALLE_ARREGLO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_DETALLE         INT NOT NULL REFERENCES dbo.ARREGLO(ID_DETALLE),
    ID_PRODUCTO        INT NULL REFERENCES dbo.PRODUCTO(ID_PRODUCTO),
    ID_MATERIAL        INT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    CANT_PRODUCTO      INT NULL,
    CANT_MATERIAL      INT NULL,
    CONSTRAINT CK_DETALLE_ARREGLO_UNO CHECK (
        (CASE WHEN ID_PRODUCTO IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN ID_MATERIAL IS NOT NULL THEN 1 ELSE 0 END) = 1
    )
);

-- 8. INVENTARIO
CREATE TABLE IF NOT EXISTS dbo.INVENTARIO (
    ID_INVENTARIO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRODUCTO   INT NULL REFERENCES dbo.PRODUCTO(ID_PRODUCTO),
    ID_MATERIAL   INT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    ID_DETALLE    INT NULL REFERENCES dbo.ARREGLO(ID_DETALLE),
    STOCK_ACT     INT NOT NULL DEFAULT 0 CHECK (STOCK_ACT >= 0),
    STOCK_MIN     INT NOT NULL DEFAULT 0 CHECK (STOCK_MIN >= 0),
    TIPO_ALMACEN  VARCHAR(35) NOT NULL,
    UNIDAD_MEDIDA VARCHAR(50) NOT NULL,
    CONSTRAINT CK_INVENTARIO_UNO CHECK (
        (CASE WHEN ID_PRODUCTO IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN ID_MATERIAL  IS NOT NULL THEN 1 ELSE 0 END +
         CASE WHEN ID_DETALLE   IS NOT NULL THEN 1 ELSE 0 END) = 1
    )
);

-- 9. TERMINOS
CREATE TABLE IF NOT EXISTS dbo.TERMINOS (
    ID_TERMINO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    PALABRA    CITEXT NOT NULL,
    CONSTRAINT UQ_TERMINOS_PALABRA UNIQUE (PALABRA)
);

-- 10. DETALLE_TERMINO
CREATE TABLE IF NOT EXISTS dbo.DETALLE_TERMINO (
    ID_DETALLE_TERMINO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TERMINO         INT NOT NULL REFERENCES dbo.TERMINOS(ID_TERMINO),
    ID_INVENTARIO      INT NOT NULL REFERENCES dbo.INVENTARIO(ID_INVENTARIO),
    CONSTRAINT UQ_DETALLE_TERMINO UNIQUE (ID_TERMINO, ID_INVENTARIO)
);

-- 11. CLIENTE
CREATE TABLE IF NOT EXISTS dbo.CLIENTE (
    ID_CLIENTE INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE     VARCHAR(90) NOT NULL,
    NUM_WSP    VARCHAR(12) NOT NULL
);

-- 12. CREDITO_CLIENTE (ID_VENTA se agrega como FK más abajo)
CREATE TABLE IF NOT EXISTS dbo.CREDITO_CLIENTE (
    ID_CREDITO_CLIENTE INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLIENTE         INT NOT NULL REFERENCES dbo.CLIENTE(ID_CLIENTE),
    ID_INVENTARIO      INT NULL REFERENCES dbo.INVENTARIO(ID_INVENTARIO),
    ID_VENTA           INT NULL,
    MONTO              NUMERIC(10,2) NOT NULL CHECK (MONTO > 0 AND MONTO <= 1000000),
    ESTADO             VARCHAR(12) NOT NULL CHECK (ESTADO IN ('ACTIVO','CANJEADO')),
    FECHA              TIMESTAMP(2) NOT NULL,
    FECHA_VENCIMIENTO  TIMESTAMP(2) NULL,
    ID_USUARIO         INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO)
);

-- 13. VENTA (ID_PEDIDO se agrega como FK más abajo)
CREATE TABLE IF NOT EXISTS dbo.VENTA (
    ID_VENTA         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CAJA          INT NULL REFERENCES dbo.CAJA(ID_CAJA),
    ID_DETALLE_VENTA INT NULL,
    ID_PEDIDO        INT NULL,
    TOTAL            NUMERIC(10,2) NOT NULL CHECK (TOTAL >= 0 AND TOTAL <= 1000000),
    TIPO_PAGO        VARCHAR(8) NULL CHECK (TIPO_PAGO IN ('YAPE','EFECTIVO','CREDITO')),
    ESTADO           VARCHAR(12) NOT NULL CHECK (ESTADO IN ('COTIZACION','VENDIDO','CANCELADO')),
    FECHA_VENTA      TIMESTAMP(2) NOT NULL
);

-- 14. DETALLE_VENTA
CREATE TABLE IF NOT EXISTS dbo.DETALLE_VENTA (
    ID_DETALLE_VENTA  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_INVENTARIO     INT NOT NULL REFERENCES dbo.INVENTARIO(ID_INVENTARIO),
    ID_CLIENTE        INT NULL REFERENCES dbo.CLIENTE(ID_CLIENTE),
    CANTIDAD          INT NOT NULL CHECK (CANTIDAD > 0),
    COSTO_UNITARIO    NUMERIC(10,2) NOT NULL CHECK (COSTO_UNITARIO >= 0 AND COSTO_UNITARIO <= 1000000),
    SUBTOTAL          NUMERIC(10,2) NOT NULL CHECK (SUBTOTAL >= 0 AND SUBTOTAL <= 1000000),
    ID_CAJA           INT NULL REFERENCES dbo.CAJA(ID_CAJA),
    ID_VENTA          INT NULL REFERENCES dbo.VENTA(ID_VENTA),
    FECHA_CREACION    TIMESTAMP(2) NOT NULL,
    FECHA_VENCIMIENTO TIMESTAMP(2) NULL,
    ESTADO            VARCHAR(12) NOT NULL CHECK (ESTADO IN ('COTIZACION','VENDIDO','CANCELADO'))
);

-- 15. PEDIDOS
CREATE TABLE IF NOT EXISTS dbo.PEDIDOS (
    ID_PEDIDO           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CLIENTE          INT NULL REFERENCES dbo.CLIENTE(ID_CLIENTE),
    NOMBRE_PAGA         VARCHAR(90) NOT NULL,
    NOMBRE_RECOGE       VARCHAR(90) NULL,
    CELULAR             VARCHAR(12) NOT NULL,
    FECHA_RECOJO        DATE NOT NULL,
    HORA_RECOJO         VARCHAR(5) NULL,
    ADELANTO            NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (ADELANTO >= 0 AND ADELANTO <= 1000000),
    TOTAL               NUMERIC(10,2) NOT NULL CHECK (TOTAL > 0 AND TOTAL <= 1000000),
    ESTADO              VARCHAR(20) NOT NULL CHECK (ESTADO IN ('PENDIENTE','COMPLETO','RECOGIDO','CANCELADO')),
    ESTADO_PRODUCCION   VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE'
                        CHECK (ESTADO_PRODUCCION IN ('PENDIENTE','HECHO','CANCELADO')),
    ID_USUARIO          INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    FECHA_CREACION      TIMESTAMP(2) NOT NULL,
    FECHA_LIMITE_CANJE  TIMESTAMP(2) NOT NULL,
    FECHA_LIMITE_RECOJO TIMESTAMP(2) NOT NULL,
    FECHA_LIMITE_PAGO   TIMESTAMP(2) NOT NULL,
    FECHA_PAGO_TOTAL    TIMESTAMP(2) NULL
);

-- 16. DETALLE_PEDIDO
CREATE TABLE IF NOT EXISTS dbo.DETALLE_PEDIDO (
    ID_DETALLE_PEDIDO INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PEDIDO         INT NOT NULL REFERENCES dbo.PEDIDOS(ID_PEDIDO),
    ID_INVENTARIO     INT NOT NULL REFERENCES dbo.INVENTARIO(ID_INVENTARIO),
    CANTIDAD          INT NOT NULL CHECK (CANTIDAD > 0),
    COSTO_UNITARIO    NUMERIC(10,2) NOT NULL CHECK (COSTO_UNITARIO >= 0 AND COSTO_UNITARIO <= 1000000),
    SUBTOTAL          NUMERIC(10,2) NOT NULL CHECK (SUBTOTAL >= 0 AND SUBTOTAL <= 1000000)
);

-- 17. PROVEEDOR
CREATE TABLE IF NOT EXISTS dbo.PROVEEDOR (
    ID_PROVEEDOR INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE       VARCHAR(50) NOT NULL,
    NUMERO       VARCHAR(12) NOT NULL
);

-- 18. INGRESO
CREATE TABLE IF NOT EXISTS dbo.INGRESO (
    ID_INGRESO    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PROVEEDOR  INT NOT NULL REFERENCES dbo.PROVEEDOR(ID_PROVEEDOR),
    ID_USUARIO    INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    FECHA_INGRESO DATE NOT NULL
);

-- 19. DETALLE_INGRESO
CREATE TABLE IF NOT EXISTS dbo.DETALLE_INGRESO (
    ID_DETALLE_INGRESO     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_INGRESO             INT NOT NULL REFERENCES dbo.INGRESO(ID_INGRESO),
    ID_INVENTARIO          INT NOT NULL REFERENCES dbo.INVENTARIO(ID_INVENTARIO),
    CANTIDAD               INT NOT NULL CHECK (CANTIDAD > 0),
    PRECIO_COMPRA_UNITARIO NUMERIC(10,2) NOT NULL CHECK (PRECIO_COMPRA_UNITARIO >= 0 AND PRECIO_COMPRA_UNITARIO <= 1000000),
    SUBTOTAL               NUMERIC(10,2) NOT NULL CHECK (SUBTOTAL >= 0 AND SUBTOTAL <= 1000000),
    OBSERVACIONES          VARCHAR(100) NULL
);

-- 20. AJUSTE_INVENTARIO
CREATE TABLE IF NOT EXISTS dbo.AJUSTE_INVENTARIO (
    ID_AJUSTE  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    FECHA      TIMESTAMP(2) NOT NULL
);

-- 21. DETALLE_AJUSTE
CREATE TABLE IF NOT EXISTS dbo.DETALLE_AJUSTE (
    ID_DETALLE_AJUSTE INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_AJUSTE         INT NOT NULL REFERENCES dbo.AJUSTE_INVENTARIO(ID_AJUSTE),
    ID_INVENTARIO     INT NOT NULL REFERENCES dbo.INVENTARIO(ID_INVENTARIO),
    CANTIDAD          INT NOT NULL,
    TIPO_AJUSTE       VARCHAR(35) NOT NULL,
    MOTIVO            VARCHAR(100) NULL
);

-- 22. MOVIMIENTO_INVENTARIO
CREATE TABLE IF NOT EXISTS dbo.MOVIMIENTO_INVENTARIO (
    ID_MOVIMIENTO    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO       INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    ID_INVENTARIO    INT NOT NULL REFERENCES dbo.INVENTARIO(ID_INVENTARIO),
    FECHA_MOVIMIENTO TIMESTAMP(2) NOT NULL,
    TIPO_MOVIMIENTO  VARCHAR(10) NOT NULL CHECK (TIPO_MOVIMIENTO IN ('ENTRADA','SALIDA','AJUSTE')),
    CANTIDAD         INT NOT NULL CHECK (CANTIDAD > 0)
);

-- FKs que dependen de tablas creadas después.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_VENTA_PEDIDO' AND conrelid = 'dbo.VENTA'::regclass
    ) THEN
        ALTER TABLE dbo.VENTA ADD CONSTRAINT FK_VENTA_PEDIDO
            FOREIGN KEY (ID_PEDIDO) REFERENCES dbo.PEDIDOS(ID_PEDIDO);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'FK_CREDITO_VENTA' AND conrelid = 'dbo.CREDITO_CLIENTE'::regclass
    ) THEN
        ALTER TABLE dbo.CREDITO_CLIENTE ADD CONSTRAINT FK_CREDITO_VENTA
            FOREIGN KEY (ID_VENTA) REFERENCES dbo.VENTA(ID_VENTA);
    END IF;
END $$;
