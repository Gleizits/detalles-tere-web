-- 13. PEDIDOS
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.PEDIDOS), 0)::int) AS n
)
INSERT INTO dbo.PEDIDOS
    (ID_CLIENTE, NOMBRE_PAGA, NOMBRE_RECOGE, CELULAR, FECHA_RECOJO, HORA_RECOJO,
     ADELANTO, TOTAL, ESTADO, ESTADO_PRODUCCION, ID_USUARIO, FECHA_CREACION,
     FECHA_LIMITE_CANJE, FECHA_LIMITE_RECOJO, FECHA_LIMITE_PAGO, FECHA_PAGO_TOTAL)
SELECT cl.ID_CLIENTE,
       'Pagador demo ' || n.n,
       CASE WHEN n.n % 2 = 0 THEN 'Recogedor demo ' || n.n END,
       '97' || LPAD(n.n::text, 8, '0'),
       (TIMESTAMP '2026-11-25 09:00:00' + ((10 + n.n) * INTERVAL '1 day'))::date,
       '10:30',
       ((100 + n.n * 5) * 0.60)::numeric(10,2),
       100 + n.n * 5,
       CASE n.n % 4 WHEN 0 THEN 'PENDIENTE' WHEN 1 THEN 'COMPLETO'
                    WHEN 2 THEN 'RECOGIDO' ELSE 'CANCELADO' END,
       CASE WHEN n.n % 4 = 0 THEN 'PENDIENTE' WHEN n.n % 4 = 3 THEN 'CANCELADO' ELSE 'HECHO' END,
       u.ID_USUARIO,
       TIMESTAMP '2026-11-25 09:00:00' - (n.n * INTERVAL '1 day'),
       (TIMESTAMP '2026-11-25 09:00:00' - (n.n * INTERVAL '1 day')) + INTERVAL '3 months',
       (TIMESTAMP '2026-11-25 09:00:00' - (n.n * INTERVAL '1 day')) + INTERVAL '2 months',
       (TIMESTAMP '2026-11-25 09:00:00' - (n.n * INTERVAL '1 day')) + INTERVAL '1 month',
       CASE WHEN n.n % 4 IN (1,2)
            THEN (TIMESTAMP '2026-11-25 09:00:00' - (n.n * INTERVAL '1 day')) + INTERVAL '5 days'
       END
FROM n
JOIN _cli cl ON cl.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _cli)) + 1
JOIN _u   u  ON u.rn  = ((n.n - 1) % (SELECT COUNT(*) FROM _u)) + 1
