CREATE TEMP TABLE _term AS
SELECT ID_TERMINO, ROW_NUMBER() OVER (ORDER BY ID_TERMINO) AS rn FROM dbo.TERMINOS;

-- 9. DETALLE_TERMINO
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.DETALLE_TERMINO), 0)::int) AS n
)
INSERT INTO dbo.DETALLE_TERMINO (ID_TERMINO, ID_INVENTARIO)
SELECT t.ID_TERMINO, i.ID_INVENTARIO
FROM n
JOIN _term t ON t.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _term)) + 1
JOIN _inv  i ON i.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _inv)) + 1
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.DETALLE_TERMINO dt
    WHERE dt.ID_TERMINO = t.ID_TERMINO AND dt.ID_INVENTARIO = i.ID_INVENTARIO
)
ORDER BY n.n;

