-- 19. VENTA
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.VENTA), 0)::int) AS n
)
INSERT INTO dbo.VENTA (ID_CAJA, ID_DETALLE_VENTA, ID_PEDIDO, TOTAL, TIPO_PAGO, ESTADO, FECHA_VENTA)
SELECT CASE WHEN n.n % 7 <> 1 THEN c.ID_CAJA END,
       NULL,
       CASE WHEN n.n % 7 <> 1 AND n.n % 2 = 0 THEN p.ID_PEDIDO END,
       (18 + (n.n % 80)) * ((n.n % 5) + 1),
       CASE WHEN n.n % 7 = 1 THEN NULL
