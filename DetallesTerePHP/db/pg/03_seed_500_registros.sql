       'pc4_termino_' || LPAD(((SELECT COUNT(*) FROM dbo.TERMINOS) + n.n)::text, 4, '0')
FROM n
JOIN _u u ON u.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _u)) + 1
