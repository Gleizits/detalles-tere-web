CREATE TEMP TABLE _a AS
SELECT ID_DETALLE, ROW_NUMBER() OVER (ORDER BY ID_DETALLE) AS rn FROM dbo.ARREGLO;

-- 6. DETALLE_ARREGLO
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.DETALLE_ARREGLO), 0)::int) AS n
)
INSERT INTO dbo.DETALLE_ARREGLO (ID_DETALLE, ID_PRODUCTO, ID_MATERIAL, CANT_PRODUCTO, CANT_MATERIAL)
SELECT a.ID_DETALLE,
       CASE WHEN n.n % 2 = 1 THEN p.ID_PRODUCTO END,
       CASE WHEN n.n % 2 = 0 THEN m.ID_MATERIAL END,
       CASE WHEN n.n % 2 = 1 THEN (n.n % 5) + 1 END,
       CASE WHEN n.n % 2 = 0 THEN (n.n % 8) + 1 END
FROM n
JOIN _a a ON a.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _a)) + 1
JOIN _p p ON p.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _p)) + 1
JOIN _m m ON m.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _m)) + 1
ORDER BY n.n;

-- 7. INVENTARIO
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.INVENTARIO), 0)::int) AS n
)
INSERT INTO dbo.INVENTARIO
    (ID_PRODUCTO, ID_MATERIAL, ID_DETALLE, STOCK_ACT, STOCK_MIN, TIPO_ALMACEN, UNIDAD_MEDIDA)
SELECT CASE WHEN n.n % 3 = 1 THEN p.ID_PRODUCTO END,
       CASE WHEN n.n % 3 = 2 THEN m.ID_MATERIAL END,
       CASE WHEN n.n % 3 = 0 THEN a.ID_DETALLE END,
       20 + (n.n % 180), 5 + (n.n % 15),
       CASE n.n % 3 WHEN 1 THEN 'Productos' WHEN 2 THEN 'Materiales' ELSE 'Arreglos' END,
       CASE n.n % 5 WHEN 1 THEN 'Unidad' WHEN 2 THEN 'Paquete' WHEN 3 THEN 'Docena'
                    WHEN 4 THEN 'Cajon' ELSE 'Costal' END
FROM n
JOIN _p p ON p.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _p)) + 1
JOIN _m m ON m.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _m)) + 1
JOIN _a a ON a.rn = ((n.n - 1) % (SELECT COUNT(*) FROM _a)) + 1
ORDER BY n.n;

CREATE TEMP TABLE _inv AS
SELECT ID_INVENTARIO, ROW_NUMBER() OVER (ORDER BY ID_INVENTARIO) AS rn FROM dbo.INVENTARIO;

-- 8. TERMINOS
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.TERMINOS), 0)::int) AS n
