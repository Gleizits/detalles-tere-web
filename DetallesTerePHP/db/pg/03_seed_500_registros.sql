CREATE TEMP TABLE _m AS
SELECT ID_MATERIAL, ROW_NUMBER() OVER (ORDER BY ID_MATERIAL) AS rn FROM dbo.MATERIAL;

-- 5. ARREGLO
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.ARREGLO), 0)::int) AS n
