CREATE TEMP TABLE _u AS
SELECT ID_USUARIO, ROW_NUMBER() OVER (ORDER BY ID_USUARIO) AS rn FROM dbo.USUARIO;

-- 2. CATEGORIA
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.CATEGORIA), 0)::int) AS n
