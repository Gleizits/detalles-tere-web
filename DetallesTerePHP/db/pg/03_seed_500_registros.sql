-- 12. CAJA
WITH n AS (
    SELECT generate_series(1, GREATEST(500 - (SELECT COUNT(*) FROM dbo.CAJA), 0)::int) AS n
)
INSERT INTO dbo.CAJA
    (ID_USUARIO, MONTO_INICIAL, MONTO_FINAL, MONTO_REAL, DIFERENCIA, FECHA_APERTURA, FECHA_CIERRE)
SELECT u.ID_USUARIO, 100.00, 300.00 + n.n, 300.00 + n.n + (n.n % 7) - 3,
       ((n.n % 7) - 3)::numeric(10,2),
       TIMESTAMP '2026-11-25 09:00:00' - (n.n * INTERVAL '1 day'),
       (TIMESTAMP '2026-11-25 09:00:00' - (n.n * INTERVAL '1 day')) + INTERVAL '8 hours'
