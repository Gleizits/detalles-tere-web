-- ============================================================
-- DetallesTereTS — datos de prueba para entrega PC4
-- Objetivo: 500 registros en CADA una de las 22 tablas.
-- Idempotente: si la tabla ya tiene 500 filas no inserta nada.
-- Transaccional: si falla a mitad, ROLLBACK para no dejar datos parciales.
-- ADVERTENCIA: ejecutar solo sobre una BD de demostracion o una copia
-- del .bak. Nunca sobre la base de produccion sin backup previo.
-- ============================================================

USE DetallesTereDB;
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

BEGIN TRY
    BEGIN TRANSACTION;

-- Numeros del 1 al 500, reutilizables en todos los INSERT.
IF OBJECT_ID('tempdb..#N') IS NOT NULL DROP TABLE #N;
SELECT TOP (500)
       ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS n
INTO #N
FROM sys.all_objects a CROSS JOIN sys.all_objects b;

DECLARE @faltan INT;
DECLARE @base DATETIME2 = '2026-11-25T09:00:00';
DECLARE @hash VARCHAR(255) = '$2b$10$oKYeKvECiPs0qWM1Ap1A9eboNLPeDxlFQcvxRE.J.VJp/J/vUAdy2';
DECLARE @nU INT, @nCat INT, @nP INT, @nM INT, @nA INT, @nInv INT;
DECLARE @nTerm INT, @nProv INT, @nCli INT, @nCaja INT, @nPed INT;
DECLARE @nIng INT, @nAju INT, @nVen INT;

-- 1. USUARIO (admin del seed + 499 empleados)
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.USUARIO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.USUARIO) END;
INSERT INTO dbo.USUARIO (USERNAME, NOMBRE, APELLIDO, CORREO, CONTRASENA, ROL, ESTADO)
SELECT TOP (@faltan)
       'pc4_user_' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.USUARIO) + N.n AS VARCHAR(10)), 4),
       'Usuario',
       RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.USUARIO) + N.n AS VARCHAR(10)), 4),
       'pc4_correo_' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.USUARIO) + N.n AS VARCHAR(10)), 4) + '@detallestere.local',
       @hash, 'empleado', 1
FROM #N N
ORDER BY N.n;
SELECT ID_USUARIO, ROW_NUMBER() OVER (ORDER BY ID_USUARIO) AS rn INTO #U FROM dbo.USUARIO;
SET @nU = (SELECT COUNT(*) FROM #U);

-- 2. CATEGORIA
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.CATEGORIA) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.CATEGORIA) END;
INSERT INTO dbo.CATEGORIA (NOMBRE, DESCRIPCION)
SELECT TOP (@faltan)
       'Categoria demo ' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.CATEGORIA) + N.n AS VARCHAR(10)), 4),
       'Categoria generada para pruebas PC4'
FROM #N N
ORDER BY N.n;
SELECT ID_CATEGORIA, ROW_NUMBER() OVER (ORDER BY ID_CATEGORIA) AS rn INTO #CAT FROM dbo.CATEGORIA;
SET @nCat = (SELECT COUNT(*) FROM #CAT);

-- 3. PRODUCTO
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.PRODUCTO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.PRODUCTO) END;
INSERT INTO dbo.PRODUCTO (ID_CATEGORIA, NOMBRE, TIPO, PRECIO_COMPRA, PRECIO_VENTA)
SELECT TOP (@faltan)
       C.ID_CATEGORIA,
       'Producto demo ' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.PRODUCTO) + N.n AS VARCHAR(10)), 4),
       CASE N.n % 3 WHEN 1 THEN 'Unidad' WHEN 2 THEN 'Paquete' ELSE 'Cajon' END,
       10 + (N.n % 40), 18 + (N.n % 70)
FROM #N N
JOIN #CAT C ON C.rn = ((N.n - 1) % @nCat) + 1
ORDER BY N.n;
SELECT ID_PRODUCTO, ROW_NUMBER() OVER (ORDER BY ID_PRODUCTO) AS rn INTO #P FROM dbo.PRODUCTO;
SET @nP = (SELECT COUNT(*) FROM #P);

-- 4. MATERIAL
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.MATERIAL) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.MATERIAL) END;
INSERT INTO dbo.MATERIAL (ID_CATEGORIA, NOMBRE, TIPO, PRECIO_COMPRA, PRECIO_VENTA)
SELECT TOP (@faltan)
       C.ID_CATEGORIA,
       'Material demo ' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.MATERIAL) + N.n AS VARCHAR(10)), 4),
       CASE N.n % 4 WHEN 1 THEN 'Globo' WHEN 2 THEN 'Vela' WHEN 3 THEN 'Base' ELSE 'Papeleria' END,
       5 + (N.n % 25), 9 + (N.n % 45)
FROM #N N
JOIN #CAT C ON C.rn = ((N.n - 1) % @nCat) + 1
ORDER BY N.n;
SELECT ID_MATERIAL, ROW_NUMBER() OVER (ORDER BY ID_MATERIAL) AS rn INTO #M FROM dbo.MATERIAL;
SET @nM = (SELECT COUNT(*) FROM #M);

-- 5. ARREGLO
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.ARREGLO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.ARREGLO) END;
INSERT INTO dbo.ARREGLO (ID_CATEGORIA, NOMBRE, PRECIO_COMPRA, PRECIO_VENTA)
SELECT TOP (@faltan)
       C.ID_CATEGORIA,
       'Arreglo demo ' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.ARREGLO) + N.n AS VARCHAR(10)), 4),
       30 + (N.n % 80), 55 + (N.n % 140)
FROM #N N
JOIN #CAT C ON C.rn = ((N.n - 1) % @nCat) + 1
ORDER BY N.n;
SELECT ID_DETALLE, ROW_NUMBER() OVER (ORDER BY ID_DETALLE) AS rn INTO #A FROM dbo.ARREGLO;
SET @nA = (SELECT COUNT(*) FROM #A);

-- 6. DETALLE_ARREGLO (exactamente producto O material)
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.DETALLE_ARREGLO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.DETALLE_ARREGLO) END;
INSERT INTO dbo.DETALLE_ARREGLO (ID_DETALLE, ID_PRODUCTO, ID_MATERIAL, CANT_PRODUCTO, CANT_MATERIAL)
SELECT TOP (@faltan)
       A.ID_DETALLE,
       CASE WHEN N.n % 2 = 1 THEN P.ID_PRODUCTO END,
       CASE WHEN N.n % 2 = 0 THEN M.ID_MATERIAL END,
       CASE WHEN N.n % 2 = 1 THEN (N.n % 5) + 1 END,
       CASE WHEN N.n % 2 = 0 THEN (N.n % 8) + 1 END
FROM #N N
JOIN #A A ON A.rn = ((N.n - 1) % @nA) + 1
JOIN #P P ON P.rn = ((N.n - 1) % @nP) + 1
JOIN #M M ON M.rn = ((N.n - 1) % @nM) + 1
ORDER BY N.n;

-- 7. INVENTARIO (exactamente producto, material O arreglo)
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.INVENTARIO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.INVENTARIO) END;
INSERT INTO dbo.INVENTARIO
    (ID_PRODUCTO, ID_MATERIAL, ID_DETALLE, STOCK_ACT, STOCK_MIN, TIPO_ALMACEN, UNIDAD_MEDIDA)
SELECT TOP (@faltan)
       CASE WHEN N.n % 3 = 1 THEN P.ID_PRODUCTO END,
       CASE WHEN N.n % 3 = 2 THEN M.ID_MATERIAL END,
       CASE WHEN N.n % 3 = 0 THEN A.ID_DETALLE END,
       20 + (N.n % 180), 5 + (N.n % 15),
       CASE N.n % 3 WHEN 1 THEN 'Productos' WHEN 2 THEN 'Materiales' ELSE 'Arreglos' END,
       CASE N.n % 5 WHEN 1 THEN 'Unidad' WHEN 2 THEN 'Paquete' WHEN 3 THEN 'Docena'
                    WHEN 4 THEN 'Cajon' ELSE 'Costal' END
FROM #N N
JOIN #P P ON P.rn = ((N.n - 1) % @nP) + 1
JOIN #M M ON M.rn = ((N.n - 1) % @nM) + 1
JOIN #A A ON A.rn = ((N.n - 1) % @nA) + 1
ORDER BY N.n;
SELECT ID_INVENTARIO, ROW_NUMBER() OVER (ORDER BY ID_INVENTARIO) AS rn INTO #INV FROM dbo.INVENTARIO;
SET @nInv = (SELECT COUNT(*) FROM #INV);

-- 8. TERMINOS
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.TERMINOS) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.TERMINOS) END;
INSERT INTO dbo.TERMINOS (ID_USUARIO, PALABRA)
SELECT TOP (@faltan)
       U.ID_USUARIO,
       'pc4_termino_' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.TERMINOS) + N.n AS VARCHAR(10)), 4)
FROM #N N
JOIN #U U ON U.rn = ((N.n - 1) % @nU) + 1
ORDER BY N.n;
SELECT ID_TERMINO, ROW_NUMBER() OVER (ORDER BY ID_TERMINO) AS rn INTO #TERM FROM dbo.TERMINOS;
SET @nTerm = (SELECT COUNT(*) FROM #TERM);

-- 9. DETALLE_TERMINO (pares unicos)
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.DETALLE_TERMINO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.DETALLE_TERMINO) END;
INSERT INTO dbo.DETALLE_TERMINO (ID_TERMINO, ID_INVENTARIO)
SELECT TOP (@faltan) T.ID_TERMINO, I.ID_INVENTARIO
FROM #N N
JOIN #TERM T ON T.rn = ((N.n - 1) % @nTerm) + 1
JOIN #INV I ON I.rn = ((N.n - 1) % @nInv) + 1
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.DETALLE_TERMINO DT
    WHERE DT.ID_TERMINO = T.ID_TERMINO AND DT.ID_INVENTARIO = I.ID_INVENTARIO
)
ORDER BY N.n;

-- 10. PROVEEDOR
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.PROVEEDOR) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.PROVEEDOR) END;
INSERT INTO dbo.PROVEEDOR (NOMBRE, NUMERO)
SELECT TOP (@faltan)
       'Proveedor demo ' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.PROVEEDOR) + N.n AS VARCHAR(10)), 4),
       '99' + RIGHT('00000000' + CAST((SELECT COUNT(*) FROM dbo.PROVEEDOR) + N.n AS VARCHAR(10)), 8)
FROM #N N
ORDER BY N.n;
SELECT ID_PROVEEDOR, ROW_NUMBER() OVER (ORDER BY ID_PROVEEDOR) AS rn INTO #PROV FROM dbo.PROVEEDOR;
SET @nProv = (SELECT COUNT(*) FROM #PROV);

-- 11. CLIENTE
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.CLIENTE) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.CLIENTE) END;
INSERT INTO dbo.CLIENTE (NOMBRE, NUM_WSP)
SELECT TOP (@faltan)
       'Cliente demo ' + RIGHT('000' + CAST((SELECT COUNT(*) FROM dbo.CLIENTE) + N.n AS VARCHAR(10)), 4),
       '98' + RIGHT('00000000' + CAST((SELECT COUNT(*) FROM dbo.CLIENTE) + N.n AS VARCHAR(10)), 8)
FROM #N N
ORDER BY N.n;
SELECT ID_CLIENTE, ROW_NUMBER() OVER (ORDER BY ID_CLIENTE) AS rn INTO #CLI FROM dbo.CLIENTE;
SET @nCli = (SELECT COUNT(*) FROM #CLI);

-- 12. CAJA (todas cerradas para no chocar con UX_CAJA_ABIERTA)
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.CAJA) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.CAJA) END;
INSERT INTO dbo.CAJA
    (ID_USUARIO, MONTO_INICIAL, MONTO_FINAL, MONTO_REAL, DIFERENCIA, FECHA_APERTURA, FECHA_CIERRE)
SELECT TOP (@faltan)
       U.ID_USUARIO, 100.00, 300.00 + N.n, 300.00 + N.n + (N.n % 7) - 3,
       CAST((N.n % 7) - 3 AS DECIMAL(10,2)),
       DATEADD(DAY, -N.n, @base), DATEADD(HOUR, 8, DATEADD(DAY, -N.n, @base))
FROM #N N
JOIN #U U ON U.rn = ((N.n - 1) % @nU) + 1
ORDER BY N.n;
SELECT ID_CAJA, ROW_NUMBER() OVER (ORDER BY ID_CAJA) AS rn INTO #CAJA FROM dbo.CAJA;
SET @nCaja = (SELECT COUNT(*) FROM #CAJA);

-- 13. PEDIDOS
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.PEDIDOS) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.PEDIDOS) END;
INSERT INTO dbo.PEDIDOS
    (ID_CLIENTE, NOMBRE_PAGA, NOMBRE_RECOGE, CELULAR, FECHA_RECOJO, HORA_RECOJO,
     ADELANTO, TOTAL, ESTADO, ESTADO_PRODUCCION, ID_USUARIO, FECHA_CREACION,
     FECHA_LIMITE_CANJE, FECHA_LIMITE_RECOJO, FECHA_LIMITE_PAGO, FECHA_PAGO_TOTAL)
SELECT TOP (@faltan)
       CL.ID_CLIENTE,
       'Pagador demo ' + CAST(N.n AS VARCHAR(10)),
       CASE WHEN N.n % 2 = 0 THEN 'Recogedor demo ' + CAST(N.n AS VARCHAR(10)) END,
       '97' + RIGHT('00000000' + CAST(N.n AS VARCHAR(10)), 8),
       CAST(DATEADD(DAY, 10 + N.n, @base) AS DATE), '10:30',
       CAST((100 + N.n * 5) * 0.60 AS DECIMAL(10,2)), 100 + N.n * 5,
       CASE N.n % 4 WHEN 0 THEN 'PENDIENTE' WHEN 1 THEN 'COMPLETO'
                    WHEN 2 THEN 'RECOGIDO' ELSE 'CANCELADO' END,
       CASE WHEN N.n % 4 = 0 THEN 'PENDIENTE' WHEN N.n % 4 = 3 THEN 'CANCELADO' ELSE 'HECHO' END,
       U.ID_USUARIO, DATEADD(DAY, -N.n, @base),
       DATEADD(MONTH, 3, DATEADD(DAY, -N.n, @base)),
       DATEADD(MONTH, 2, DATEADD(DAY, -N.n, @base)),
       DATEADD(MONTH, 1, DATEADD(DAY, -N.n, @base)),
       CASE WHEN N.n % 4 IN (1, 2) THEN DATEADD(DAY, -N.n + 5, @base) END
FROM #N N
JOIN #CLI CL ON CL.rn = ((N.n - 1) % @nCli) + 1
JOIN #U U ON U.rn = ((N.n - 1) % @nU) + 1
ORDER BY N.n;
SELECT ID_PEDIDO, ROW_NUMBER() OVER (ORDER BY ID_PEDIDO) AS rn INTO #PED FROM dbo.PEDIDOS;
SET @nPed = (SELECT COUNT(*) FROM #PED);

-- 14. DETALLE_PEDIDO
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.DETALLE_PEDIDO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.DETALLE_PEDIDO) END;
INSERT INTO dbo.DETALLE_PEDIDO (ID_PEDIDO, ID_INVENTARIO, CANTIDAD, COSTO_UNITARIO, SUBTOTAL)
SELECT TOP (@faltan)
       P.ID_PEDIDO, I.ID_INVENTARIO, (N.n % 6) + 1,
       20 + (N.n % 60), (20 + (N.n % 60)) * ((N.n % 6) + 1)
FROM #N N
JOIN #PED P ON P.rn = ((N.n - 1) % @nPed) + 1
JOIN #INV I ON I.rn = ((N.n - 1) % @nInv) + 1
ORDER BY N.n;

-- 15. INGRESO
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.INGRESO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.INGRESO) END;
INSERT INTO dbo.INGRESO (ID_PROVEEDOR, ID_USUARIO, FECHA_INGRESO)
SELECT TOP (@faltan)
       PV.ID_PROVEEDOR, A.ID_USUARIO, CAST(DATEADD(DAY, -N.n, @base) AS DATE)
FROM #N N
JOIN #PROV PV ON PV.rn = ((N.n - 1) % @nProv) + 1
CROSS APPLY (
    SELECT TOP (1) ID_USUARIO
    FROM dbo.USUARIO
    WHERE ROL = 'admin'
    ORDER BY ID_USUARIO
) A
ORDER BY N.n;
SELECT ID_INGRESO, ROW_NUMBER() OVER (ORDER BY ID_INGRESO) AS rn INTO #ING FROM dbo.INGRESO;
SET @nIng = (SELECT COUNT(*) FROM #ING);

-- 16. DETALLE_INGRESO
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.DETALLE_INGRESO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.DETALLE_INGRESO) END;
INSERT INTO dbo.DETALLE_INGRESO
    (ID_INGRESO, ID_INVENTARIO, CANTIDAD, PRECIO_COMPRA_UNITARIO, SUBTOTAL, OBSERVACIONES)
SELECT TOP (@faltan)
       IG.ID_INGRESO, I.ID_INVENTARIO, (N.n % 9) + 1,
       5 + (N.n % 30), (5 + (N.n % 30)) * ((N.n % 9) + 1),
       'Lote demo ' + CAST(N.n AS VARCHAR(10))
FROM #N N
JOIN #ING IG ON IG.rn = ((N.n - 1) % @nIng) + 1
JOIN #INV I ON I.rn = ((N.n - 1) % @nInv) + 1
ORDER BY N.n;

-- 17. AJUSTE_INVENTARIO
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.AJUSTE_INVENTARIO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.AJUSTE_INVENTARIO) END;
INSERT INTO dbo.AJUSTE_INVENTARIO (ID_USUARIO, FECHA)
SELECT TOP (@faltan) U.ID_USUARIO, DATEADD(DAY, -N.n, @base)
FROM #N N
JOIN #U U ON U.rn = ((N.n - 1) % @nU) + 1
ORDER BY N.n;
SELECT ID_AJUSTE, ROW_NUMBER() OVER (ORDER BY ID_AJUSTE) AS rn INTO #AJU FROM dbo.AJUSTE_INVENTARIO;
SET @nAju = (SELECT COUNT(*) FROM #AJU);

-- 18. DETALLE_AJUSTE
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.DETALLE_AJUSTE) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.DETALLE_AJUSTE) END;
INSERT INTO dbo.DETALLE_AJUSTE (ID_AJUSTE, ID_INVENTARIO, CANTIDAD, TIPO_AJUSTE, MOTIVO)
SELECT TOP (@faltan)
       A.ID_AJUSTE, I.ID_INVENTARIO, (N.n % 5) + 1,
       CASE N.n % 3 WHEN 0 THEN 'ENTRADA' WHEN 1 THEN 'SALIDA' ELSE 'CORRECCION' END,
       'Ajuste demo ' + CAST(N.n AS VARCHAR(10))
FROM #N N
JOIN #AJU A ON A.rn = ((N.n - 1) % @nAju) + 1
JOIN #INV I ON I.rn = ((N.n - 1) % @nInv) + 1
ORDER BY N.n;

-- 19. VENTA
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.VENTA) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.VENTA) END;
INSERT INTO dbo.VENTA (ID_CAJA, ID_DETALLE_VENTA, ID_PEDIDO, TOTAL, TIPO_PAGO, ESTADO, FECHA_VENTA)
SELECT TOP (@faltan)
       CASE WHEN N.n % 7 <> 1 THEN C.ID_CAJA END, NULL,
       CASE WHEN N.n % 7 <> 1 AND N.n % 2 = 0 THEN P.ID_PEDIDO END,
       (18 + (N.n % 80)) * ((N.n % 5) + 1),
       CASE WHEN N.n % 7 = 1 THEN NULL
            ELSE CASE N.n % 3 WHEN 0 THEN 'CREDITO'
                              WHEN 1 THEN 'EFECTIVO' ELSE 'YAPE' END END,
       CASE N.n % 7 WHEN 0 THEN 'CANCELADO' WHEN 1 THEN 'COTIZACION' ELSE 'VENDIDO' END,
       DATEADD(HOUR, N.n % 8, DATEADD(DAY, -N.n, @base))
FROM #N N
JOIN #CAJA C ON C.rn = ((N.n - 1) % @nCaja) + 1
JOIN #PED P ON P.rn = ((N.n - 1) % @nPed) + 1
ORDER BY N.n;
SELECT ID_VENTA, ID_CAJA, ESTADO, FECHA_VENTA,
       ROW_NUMBER() OVER (ORDER BY ID_VENTA) AS rn
INTO #VEN
FROM dbo.VENTA;
SET @nVen = (SELECT COUNT(*) FROM #VEN);

-- 20. DETALLE_VENTA
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.DETALLE_VENTA) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.DETALLE_VENTA) END;
INSERT INTO dbo.DETALLE_VENTA
    (ID_INVENTARIO, ID_CLIENTE, CANTIDAD, COSTO_UNITARIO, SUBTOTAL, ID_CAJA, ID_VENTA,
     FECHA_CREACION, FECHA_VENCIMIENTO, ESTADO)
SELECT TOP (@faltan)
       I.ID_INVENTARIO, CL.ID_CLIENTE, (N.n % 5) + 1,
       18 + (N.n % 80), (18 + (N.n % 80)) * ((N.n % 5) + 1),
       V.ID_CAJA, V.ID_VENTA, V.FECHA_VENTA,
       CASE WHEN V.ESTADO = 'COTIZACION' THEN DATEADD(HOUR, 24, V.FECHA_VENTA) END,
       V.ESTADO
FROM #N N
JOIN #VEN V ON V.rn = ((N.n - 1) % @nVen) + 1
JOIN #INV I ON I.rn = ((N.n - 1) % @nInv) + 1
JOIN #CLI CL ON CL.rn = ((N.n - 1) % @nCli) + 1
ORDER BY N.n;

-- La cabecera referencial apunta a la primera línea registrada de cada venta.
UPDATE V
SET ID_DETALLE_VENTA = D.ID_DETALLE_VENTA
FROM dbo.VENTA V
JOIN dbo.DETALLE_VENTA D ON D.ID_VENTA = V.ID_VENTA
WHERE V.ID_DETALLE_VENTA IS NULL;

-- 21. MOVIMIENTO_INVENTARIO
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.MOVIMIENTO_INVENTARIO) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.MOVIMIENTO_INVENTARIO) END;
INSERT INTO dbo.MOVIMIENTO_INVENTARIO
    (ID_USUARIO, ID_INVENTARIO, FECHA_MOVIMIENTO, TIPO_MOVIMIENTO, CANTIDAD)
SELECT TOP (@faltan)
       U.ID_USUARIO, I.ID_INVENTARIO, DATEADD(DAY, -N.n, @base),
       CASE N.n % 3 WHEN 0 THEN 'ENTRADA' WHEN 1 THEN 'SALIDA' ELSE 'AJUSTE' END,
       (N.n % 12) + 1
FROM #N N
JOIN #U U ON U.rn = ((N.n - 1) % @nU) + 1
JOIN #INV I ON I.rn = ((N.n - 1) % @nInv) + 1
ORDER BY N.n;

-- 22. CREDITO_CLIENTE
SET @faltan = CASE WHEN (SELECT COUNT(*) FROM dbo.CREDITO_CLIENTE) >= 500 THEN 0 ELSE 500 - (SELECT COUNT(*) FROM dbo.CREDITO_CLIENTE) END;
INSERT INTO dbo.CREDITO_CLIENTE
    (ID_CLIENTE, ID_INVENTARIO, MONTO, ESTADO, FECHA, FECHA_VENCIMIENTO, ID_USUARIO)
SELECT TOP (@faltan)
       CL.ID_CLIENTE, CASE WHEN N.n % 2 = 1 THEN I.ID_INVENTARIO END, 10 + (N.n % 90),
       CASE WHEN N.n % 2 = 0 THEN 'ACTIVO' ELSE 'CANJEADO' END,
       DATEADD(DAY, -N.n, @base),
       DATEADD(MONTH, 3, DATEADD(DAY, -N.n, @base)), U.ID_USUARIO
FROM #N N
JOIN #CLI CL ON CL.rn = ((N.n - 1) % @nCli) + 1
JOIN #INV I ON I.rn = ((N.n - 1) % @nInv) + 1
JOIN #U U ON U.rn = ((N.n - 1) % @nU) + 1
ORDER BY N.n;

-- Validacion: las 22 tablas deben mostrar 500.
SELECT 'USUARIO' AS TABLA, COUNT(*) AS REGISTROS FROM dbo.USUARIO
UNION ALL SELECT 'CAJA', COUNT(*) FROM dbo.CAJA
UNION ALL SELECT 'CATEGORIA', COUNT(*) FROM dbo.CATEGORIA
UNION ALL SELECT 'PRODUCTO', COUNT(*) FROM dbo.PRODUCTO
UNION ALL SELECT 'MATERIAL', COUNT(*) FROM dbo.MATERIAL
UNION ALL SELECT 'ARREGLO', COUNT(*) FROM dbo.ARREGLO
UNION ALL SELECT 'DETALLE_ARREGLO', COUNT(*) FROM dbo.DETALLE_ARREGLO
UNION ALL SELECT 'INVENTARIO', COUNT(*) FROM dbo.INVENTARIO
UNION ALL SELECT 'TERMINOS', COUNT(*) FROM dbo.TERMINOS
UNION ALL SELECT 'DETALLE_TERMINO', COUNT(*) FROM dbo.DETALLE_TERMINO
UNION ALL SELECT 'CLIENTE', COUNT(*) FROM dbo.CLIENTE
UNION ALL SELECT 'CREDITO_CLIENTE', COUNT(*) FROM dbo.CREDITO_CLIENTE
UNION ALL SELECT 'VENTA', COUNT(*) FROM dbo.VENTA
UNION ALL SELECT 'DETALLE_VENTA', COUNT(*) FROM dbo.DETALLE_VENTA
UNION ALL SELECT 'PEDIDOS', COUNT(*) FROM dbo.PEDIDOS
UNION ALL SELECT 'DETALLE_PEDIDO', COUNT(*) FROM dbo.DETALLE_PEDIDO
UNION ALL SELECT 'PROVEEDOR', COUNT(*) FROM dbo.PROVEEDOR
UNION ALL SELECT 'INGRESO', COUNT(*) FROM dbo.INGRESO
UNION ALL SELECT 'DETALLE_INGRESO', COUNT(*) FROM dbo.DETALLE_INGRESO
UNION ALL SELECT 'AJUSTE_INVENTARIO', COUNT(*) FROM dbo.AJUSTE_INVENTARIO
UNION ALL SELECT 'DETALLE_AJUSTE', COUNT(*) FROM dbo.DETALLE_AJUSTE
UNION ALL SELECT 'MOVIMIENTO_INVENTARIO', COUNT(*) FROM dbo.MOVIMIENTO_INVENTARIO
ORDER BY TABLA;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO
